//! gen-howto: regenerate `src/howto.gen.md` from the clap surface + each
//! command's worked-example file under `docs/examples/`, plus the multi-command
//! scenario files under `examples/`.
//!
//! The command TREE (groups, names, about, flags) comes from `carpenter::app::cli()`
//! (recursed into nested groups). The EXAMPLE blocks come from
//! `docs/examples/<module>/<name>.md`, keyed `<module>::<name>` so groups with
//! same-named leaves (e.g. `course::create` vs `lesson::create`) don't collide.
//! `self <verb>` leaves (adr/027) dispatch to fns living in other modules, so
//! they resolve through [`SELF_EXAMPLES`] instead of the default key.
//! That file is the single source — build.rs enforces its presence per command fn
//! (adr/007 update), and nothing is scraped from `///` anymore. The SCENARIOS
//! (`examples/*.md`, each gated to ≥3 distinct command fns by build.rs) are
//! appended under `## Scenarios` (adr/013).

use std::collections::{HashMap, HashSet};
use std::path::{Path, PathBuf};

use carpenter::app;

/// Write the generated manual to `src/howto.gen.md`.
pub fn run() -> anyhow::Result<()> {
    let manual = generate();
    let path = crate::paths::workspace_root().join("src/howto.gen.md");
    std::fs::write(&path, manual)?;
    println!("gen-howto: wrote {}", path.display());
    Ok(())
}

/// Produce the manual text (clap surface + each command's fenced example).
pub fn generate() -> String {
    let root = app::cli();
    let examples = collect_examples();
    let global_names: HashSet<String> = root
        .get_arguments()
        .filter_map(|a| a.get_long().map(|l| l.to_string()))
        .collect();

    let mut out = String::new();
    out.push_str("# carpenter — howto\n\n");
    out.push_str("<!-- Generated by `cargo xtask gen-howto`. Do not hand-edit. -->\n\n");

    out.push_str("## global flags\n\n");
    for f in root.get_arguments().filter(|a| !a.is_positional()) {
        push_flag(&mut out, f);
    }
    out.push('\n');

    for sub in root.get_subcommands() {
        render(sub, sub.get_name(), 2, &mut out, &examples, &global_names);
    }

    // End-to-end scenario workflows (`examples/*.md`), embedded verbatim with
    // headings demoted +2 so they nest under `## Scenarios` (adr/013).
    let scenarios = collect_scenarios();
    if !scenarios.is_empty() {
        out.push_str("## Scenarios\n\n");
        out.push_str(
            "Multi-command workflows composed toward one goal \
             ([adr/013](../docs/adr/013-compile-enforced-scenarios.md)). These are \
             **illustrative examples**: every filename, slug, and path (including \
             `<root>/…`) is a placeholder pattern to adapt — none exist on disk; \
             do not read, create, or navigate to them.\n\n",
        );
        for (_name, body) in scenarios {
            out.push_str(&demote_headings(&body));
            out.push('\n');
        }
    }
    out
}

/// Render one command (group or leaf). `module` is the top-level command name
/// (the source file stem), used to look up `<module>::<leaf>` examples (self
/// leaves resolve via [`SELF_EXAMPLES`]).
fn render(
    cmd: &clap::Command,
    module: &str,
    depth: usize,
    out: &mut String,
    examples: &HashMap<String, String>,
    global_names: &HashSet<String>,
) {
    let name = cmd.get_name();
    let heading = "#".repeat(depth);
    out.push_str(&format!("{heading} {name}\n\n"));
    let about = cmd.get_about().map(|s| s.to_string()).unwrap_or_default();
    if !about.is_empty() {
        out.push_str(&format!("{about}\n\n"));
    }
    let own_flags: Vec<_> = cmd
        .get_arguments()
        .filter(|a| !a.is_positional())
        .filter(|a| {
            a.get_long()
                .map(|l| !global_names.contains(l))
                .unwrap_or(true)
        })
        .collect();
    if own_flags.is_empty() {
        out.push_str("_flags: none_\n\n");
    } else {
        for f in &own_flags {
            push_flag(out, f);
        }
        out.push('\n');
    }
    let subs: Vec<_> = cmd.get_subcommands().collect();
    if subs.is_empty() {
        if let Some(ex) = examples.get(&example_key(module, name)) {
            out.push_str(ex.trim());
            out.push_str("\n\n");
        }
    } else {
        for child in subs {
            render(child, module, depth + 1, out, examples, global_names);
        }
    }
}

fn push_flag(out: &mut String, f: &clap::Arg) {
    let short = f.get_short().map(|s| format!("-{s}, ")).unwrap_or_default();
    let long = f.get_long().map(|l| format!("--{l}")).unwrap_or_default();
    let value = f
        .get_value_names()
        .map(|vs| vs.join(","))
        .map(|v| format!(" <{v}>"))
        .unwrap_or_default();
    let help = f.get_help().map(|h| h.to_string()).unwrap_or_default();
    out.push_str(&format!("- `{short}{long}{value}` — {help}\n"));
}

/// `self <verb>` leaf → worked-example key (`docs/examples/<module>/<fn>.md`).
/// The `self` umbrella (adr/027) dispatches to install-lifecycle command fns
/// living in their own modules, so the default `<module>::<leaf>` key (module =
/// `self`) misses. MUST stay in sync with the `self_group`/`self_cmd` dispatch
/// in `src/app.rs` and with `SELF_VERBS` in `build.rs` (the scenario gate's
/// copy — build.rs cannot depend on this crate).
const SELF_EXAMPLES: &[(&str, &str)] = &[
    ("install", "install::install"),
    ("upgrade", "upgrade::upgrade"),
    ("uninstall", "uninstall::uninstall"),
    ("register", "register::register"),
    ("deregister", "deregister::deregister"),
    ("list", "installs::list"),
    ("remove", "installs::remove"),
    ("link", "link::register"),
];

/// Example-map key for a leaf: `self <verb>` resolves through
/// [`SELF_EXAMPLES`]; every other leaf is `<module>::<leaf>`.
fn example_key(module: &str, leaf: &str) -> String {
    if module == "self" {
        if let Some((_, key)) = SELF_EXAMPLES.iter().find(|(v, _)| *v == leaf) {
            return (*key).to_string();
        }
    }
    format!("{module}::{leaf}")
}

fn collect_examples() -> HashMap<String, String> {
    let dir = crate::paths::workspace_root().join("docs/examples");
    let mut map = HashMap::new();
    for path in walk_md(&dir) {
        let module = path
            .parent()
            .and_then(|p| p.file_name())
            .map(|s| s.to_string_lossy().to_string())
            .unwrap_or_default();
        let name = path
            .file_stem()
            .map(|s| s.to_string_lossy().to_string())
            .unwrap_or_default();
        if let Ok(text) = std::fs::read_to_string(&path) {
            map.insert(format!("{module}::{name}"), text);
        }
    }
    map
}

fn walk_md(dir: &Path) -> Vec<PathBuf> {
    // Layout is exactly two levels: <dir>/<module>/<name>.md
    let mut out = Vec::new();
    let Ok(modules) = std::fs::read_dir(dir) else {
        return out;
    };
    for m in modules.flatten() {
        let mp = m.path();
        if !mp.is_dir() {
            continue;
        }
        let Ok(entries) = std::fs::read_dir(&mp) else {
            continue;
        };
        for e in entries.flatten() {
            let p = e.path();
            if p.extension().map(|x| x == "md").unwrap_or(false) {
                out.push(p);
            }
        }
    }
    out
}

/// Collect scenario files (`examples/*.md`, flat) as `(filename, text)`, sorted
/// by filename for deterministic output. Each is embedded verbatim (with
/// headings demoted) into the manual's `## Scenarios` section (adr/013).
fn collect_scenarios() -> Vec<(String, String)> {
    let dir = crate::paths::workspace_root().join("examples");
    let mut out: Vec<(String, String)> = Vec::new();
    for path in walk_md_flat(&dir) {
        let name = path
            .file_name()
            .map(|s| s.to_string_lossy().to_string())
            .unwrap_or_default();
        if let Ok(text) = std::fs::read_to_string(&path) {
            out.push((name, text));
        }
    }
    out.sort_by(|a, b| a.0.cmp(&b.0));
    out
}

/// Top-level `<dir>/*.md` files (scenarios are flat — one file per workflow).
fn walk_md_flat(dir: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let Ok(entries) = std::fs::read_dir(dir) else {
        return out;
    };
    for e in entries.flatten() {
        let p = e.path();
        if p.is_file() && p.extension().map(|x| x == "md").unwrap_or(false) {
            out.push(p);
        }
    }
    out
}

/// Demote every column-0 markdown heading by 2 levels (`# `→`### `, `## `→
/// `#### `…) so a scenario file nests cleanly under the manual's `## Scenarios`
/// heading. Headings inside fenced code blocks are left untouched. The prose is
/// otherwise byte-verbatim (mirrors `skill::manual_body`'s H1 strip — a
/// mechanical shift, not a rewrite).
fn demote_headings(text: &str) -> String {
    let mut out = String::new();
    let mut in_fence = false;
    for line in text.lines() {
        if line.trim_start().starts_with("```") {
            in_fence = !in_fence;
            out.push_str(line);
            out.push('\n');
            continue;
        }
        if !in_fence && line.starts_with('#') {
            let n = line.chars().take_while(|&c| c == '#').count();
            if n < 6 {
                out.push_str("##");
            }
        }
        out.push_str(line);
        out.push('\n');
    }
    out
}

#[cfg(all(test, not(feature = "dev")))]
#[test]
fn howto_gen_md_is_fresh() {
    let generated = generate();
    let committed = include_str!("../../src/howto.gen.md");
    assert_eq!(
        generated, committed,
        "src/howto.gen.md is stale; run `cargo xtask gen-howto`"
    );
}

#[cfg(all(test, not(feature = "dev")))]
#[test]
fn howto_includes_scenarios() {
    // At least one scenario ships (adr/013 global floor); the manual must carry
    // the section + every scenario's (demoted) title.
    let generated = generate();
    assert!(
        generated.contains("## Scenarios"),
        "manual missing the ## Scenarios section"
    );
    assert!(
        generated.contains("### Build a course end-to-end"),
        "scenario title not demoted+inlined under ## Scenarios"
    );
}

#[cfg(all(test, not(feature = "dev")))]
#[test]
fn howto_excludes_dev_surface() {
    // gen-howto runs in the xtask build, which links carpenter WITHOUT the
    // `dev` feature, so dev-only surface must never reach the committed manual
    // (and thus the inlined SKILL.md). Pins the adr/016 invariant.
    let generated = generate();
    assert!(
        !generated.contains("capture-example"),
        "dev-only `--capture-example` flag leaked into howto.gen.md"
    );
    assert!(
        !generated.contains("DEV ONLY"),
        "dev-only help text leaked into howto.gen.md"
    );
    assert!(
        !generated.contains("## dev"),
        "dev-only `dev` group leaked into howto.gen.md"
    );
    assert!(
        !generated.contains("dev register") && !generated.contains("dev upgrade"),
        "dev-only register/upgrade leaked into howto.gen.md"
    );
}

#[cfg(all(test, not(feature = "dev")))]
#[test]
fn self_leaves_all_resolve_to_examples() {
    // The `self` lookup is an explicit map, so a leaf added without a map
    // entry (or a map entry renamed away from its atom) must fail loudly here —
    // not silently drop the example from the manual the way the pre-map
    // `<module>::<leaf>` lookup did.
    let root = app::cli();
    let self_group = root
        .get_subcommands()
        .find(|c| c.get_name() == "self")
        .expect("self group exists");
    let examples = collect_examples();
    for leaf in self_group.get_subcommands() {
        let key = example_key("self", leaf.get_name());
        assert!(
            examples.contains_key(&key),
            "self {} → {key}: no example atom under docs/examples/",
            leaf.get_name()
        );
    }
}
